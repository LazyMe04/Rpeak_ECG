// Lint rules chosen to catch defects, not to restyle code.
//
// There was no config before G16, which is defensible for one author: the code
// was already consistent. The reason to add it now is that consistency was
// keeping itself, and the rules below are the ones that catch a class of bug
// the tests cannot see -- a missing hook dependency that makes a panel read a
// stale language, an effect with no cleanup, a promise nobody awaits.
//
// Deliberately *not* enabled: stylistic rules (indentation, quotes, semicolons)
// are Prettier's job, and a lint run that fails on formatting teaches people to
// ignore the lint run.
import js from "@eslint/js";
import tseslint from "typescript-eslint";
import reactHooks from "eslint-plugin-react-hooks";
import globals from "globals";

export default tseslint.config(
  {
    ignores: [
      "dist/**",
      "src-tauri/target/**",
      "node_modules/**",
      // Generated by `npm run icons`, not hand-edited.
      "src-tauri/icons/**",
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ["**/*.{ts,tsx}"],
    plugins: { "react-hooks": reactHooks },
    languageOptions: {
      ecmaVersion: 2023,
      globals: { ...globals.browser, ...globals.node },
      // Typed linting: `no-floating-promises` needs to know a value is a
      // promise, and the project already has the tsconfig for it.
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      // The two rules that would have caught real defects in this project: a
      // hook reading a value that is not in its dependency list (the model
      // card's stale architecture labels) and an effect with no cleanup (the
      // scroll spy measuring a detached element).
      ...reactHooks.configs.recommended.rules,
      // Three of the preset's rules are prerequisites for the React Compiler,
      // not correctness rules for hand-written React, and this project does not
      // enable the compiler:
      //
      // - `refs`: flags `ref.current = x` in the render body. The engine is a
      //   lazily-created object and the panel mirror is read only from event
      //   handlers, both of which are the documented escape hatches; the rule
      //   assumes a compiler that can prove otherwise.
      // - `purity`: flags `Date.now()` during render. The report panel renders
      //   a live elapsed time, which is deliberately a function of the clock.
      // - `set-state-in-effect`: flags resetting state when a toggle turns off.
      //   The alternative is deriving four pieces of state in every consumer,
      //   which is more code, not less.
      //
      // Turning these off is a decision about this codebase, not a claim that
      // they are wrong; if the compiler is ever enabled they come back first.
      "react-hooks/refs": "off",
      "react-hooks/purity": "off",
      "react-hooks/set-state-in-effect": "off",
      // A dropped promise is how a worker's failure becomes silence: the
      // classifier panel would sit at "classifying" with nothing happening.
      "@typescript-eslint/no-floating-promises": "error",
      // `any` in the smoke scripts is understandable (CDP returns whatever it
      // returns); `any` in src/ usually means an untyped boundary.
      "@typescript-eslint/no-explicit-any": "warn",
      // Unused code is usually a refactor someone did not finish.
      "@typescript-eslint/no-unused-vars": [
        "error",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_" },
      ],
    },
  },
  {
    // The smoke scripts drive an untyped protocol and read the DOM by string;
    // the strictness that matters in src/ is noise here.
    files: ["scripts/**/*.ts"],
    rules: {
      "@typescript-eslint/no-explicit-any": "off",
      "@typescript-eslint/no-non-null-assertion": "off",
    },
  },
  {
    files: ["scripts/**/*.ts"],
    languageOptions: { globals: { ...globals.node, WebSocket: "readonly", fetch: "readonly" } },
  },
);
